"""Markdown outputs: a per-build report and the project's data card (DATA_SOURCES.md)."""

from __future__ import annotations

import pandas as pd

from aidetect_train.data.pipeline import BuildResult

_DOC_ORDER = ["train_clf", "train_meta", "calib", "test", "ood"]


def _table(frame: pd.DataFrame) -> str:
    """Render a small frame as a GitHub markdown table (no extra dependency)."""
    cols = [str(c) for c in frame.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in frame.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def _crosstab(frame: pd.DataFrame, by: str) -> str:
    table = pd.crosstab(frame[by], [frame["split"], frame["label"]])
    # Columns are a (split, label) MultiIndex; flatten to "split/label".
    table.columns = ["/".join(map(str, column)) for column in table.columns]
    ordered = [c for s in _DOC_ORDER for c in table.columns if c.startswith(s + "/")]
    return _table(table[ordered].reset_index())


def build_report(result: BuildResult) -> str:
    """Counts, cleaning and dedup statistics, and leakage results for one build."""
    df = result.frame
    parts = [
        f"# Build report: {result.manifest['name']}",
        "",
        f"Created {result.manifest['created_utc']} from code commit "
        f"`{str(result.manifest['code_commit'])[:12]}`.",
        "",
        f"**Leakage checks:** {result.leakage.summary()}",
        "",
        "## Documents per split and label",
        "",
        _table(
            pd.crosstab(df["split"], df["label"])
            .reindex(_DOC_ORDER)
            .fillna(0)
            .astype(int)
            .reset_index()
        ),
        "",
        "## Sources",
        "",
    ]
    rows = []
    for r in result.sources:
        dropped = ", ".join(f"{k}: {v}" for k, v in r.clean.dropped.items()) or "none"
        kept = int((df["source"] == r.spec.id).sum())
        rows.append(
            {
                "source": r.spec.id,
                "use": r.spec.use,
                "licence": r.spec.licence,
                "loaded": r.loaded,
                "subsampled": r.after_subsample,
                "dropped in cleaning": dropped,
                "in final build": kept,
            }
        )
    parts += [_table(pd.DataFrame(rows)), ""]
    d = result.dedup
    parts += [
        "## Deduplication",
        "",
        f"- exact duplicates removed: {d.exact_dropped}",
        f"- near-duplicate clusters spanning groups: {d.near_clusters}",
        f"- documents dropped to keep evaluation sets unseen: {d.dropped_to_protect_eval}",
        f"- documents dropped for conflicting labels: {d.dropped_label_conflict}",
        f"- groups merged: {d.groups_merged}",
        "",
    ]
    for by in ("source", "domain", "generator_family", "writer_l1", "edit_type"):
        parts += [f"## By {by.replace('_', ' ')}", "", _crosstab(df, by), ""]
    return "\n".join(parts)


def data_card(result: BuildResult) -> str:
    """The project's DATA_SOURCES.md: every source, its licence and how it is used."""
    df = result.frame
    lines = [
        "# Data sources",
        "",
        "Generated by `aidetect-data build` from the source registry "
        "(`training/configs/sources.yaml`) and the build manifest. Do not edit by hand.",
        "",
        f"Build `{result.manifest['name']}`, {result.manifest['created_utc']}.",
        "",
        "Licences were checked automatically against the licence text shipped with each "
        "source. Sources without a published licence are used for evaluation only.",
        "",
    ]
    if any(r.spec.noncommercial and r.spec.use == "train" for r in result.sources):
        lines += [
            "> **Non-commercial.** Some training data is licensed for non-commercial use "
            "only, so models trained on this build may not be used commercially.",
            "",
        ]
    rows = []
    for r in result.sources:
        rows.append(
            {
                "source": r.spec.name,
                "licence": r.spec.licence,
                "use": r.spec.use + (f" ({r.spec.ood_set})" if r.spec.ood_set else ""),
                "revision": f"`{r.spec.revision[:12]}`",
                "documents": int((df["source"] == r.spec.id).sum()),
            }
        )
    lines += [_table(pd.DataFrame(rows)), "", "## Attribution and notes", ""]
    for r in result.sources:
        lines += [f"### {r.spec.name}", "", f"- Location: <{r.spec.location}>"]
        lines += [f"- Licence: {r.spec.licence} ({r.audit.message})"]
        lines += [f"- Citation: {r.spec.attribution}"]
        if r.spec.notes:
            lines += [f"- Notes: {r.spec.notes}"]
        lines += [""]
    return "\n".join(lines)
